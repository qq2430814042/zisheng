const FONT_STACK = '"KaiTi","STKaiti","楷体","Microsoft YaHei",serif';

// 将字形绘制到 ctx 的 (cx, cy) 中心，size 为字格边长
export function drawGlyph(ctx, ch, stage, cx, cy, size) {
  if (stage === "regular") {
    ctx.font = `${Math.round(size * 0.88)}px ${FONT_STACK}`;
    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.fillText(ch, cx, cy + size * 0.02);
    return;
  }
  const data = STROKES[ch] && STROKES[ch][stage];
  if (!data) return;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(size / 100, size / 100);
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  ctx.lineWidth = STAGE_LINE_WIDTH[stage];
  for (const d of data) {
    ctx.stroke(new Path2D(d));
  }
  ctx.restore();
}
